"""Generate netherite's texture headers without a Minecraft jar.

The engine reads no PNG at runtime. Every texture it draws is a C array in
one of thirteen generated headers under magma/assets, and upstream builds
those headers from a vanilla 1.11.2 client jar you have to own. That jar is
the only thing in the whole stack a user cannot obtain by cloning, so this
script removes it.

HOW. It does not reimplement the thirteen generators. It writes a synthetic
resource pack, a real zip laid out exactly like the jar with a procedurally
drawn PNG at every path those generators read, and then runs
scripts/bootstrap_assets.sh against it. So the headers come out with the
struct shapes, symbol names, sprite counts and atlas rects the engine
already compiles against, because the engine's own generators produced them.
Only the texels differ. A stub header is then given a provenance banner
saying so, because the generator's own comment still claims Mojang art.

WHAT THE ART IS. Nothing invented. Where the engine already has a
procedural fallback it is left to use it, so a GUI item cell gets the flat
token gm_hud_pip_color would have drawn anyway. Where it draws from an
atlas, three numbers per texture decide the result and all three are
measured rather than chosen.

The colour comes from netherite's own block palette, the COLORS table in
blaze/rl/make_videos.py that colourises the semantic camera in their
README, for every block id it covers. Everything else takes the mean colour
of the vanilla 1.11.2 texture, and the two agree where both exist, exactly
for dirt at (134,96,67) and sand at (219,211,160). The second number is
that texture's texel-to-texel spread and the third is how much of it is
opaque. Matching a palette is not copying art, and without the spread a
tile at the right mean renders as a flat slab, which is what made the first
pass look like a smooth tunnel underground and like wireframe on grass.

Container panels reproduce vanilla's grey chrome, its bevel and its
recessed slot squares, so the container screens look the same and the pixel
container geometry stays aligned with the engine's screen layout.

DETERMINISM IS THE POINT. Two clones that disagree about a texel present
different model inputs even when their engine state matches. Nothing here
reads a clock, a
filesystem order or python's salted hash. Colours and noise come from an
FNV-1a of the sprite name through a fixed xorshift, and every PNG is written
at its final size in its final mode so no resampling ever runs. Generating
twice gives byte-identical headers, and `--print-digests` is how you check
that rather than take it on trust.

  uv run --no-project --with pillow python tools/stub_atlases.py \
      --netherite-home ~/netherite

MC_JAR still wins. bin/setup_deps.sh calls this only when no jar is given.
"""
