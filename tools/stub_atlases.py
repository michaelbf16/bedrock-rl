def img(w, h, fill=(0, 0, 0, 0)):
    from PIL import Image
    return Image.new("RGBA", (w, h), fill)


def px_of(im):
    return im.load()


def tone_of(name, index, total):
    """(colour, texel spread, opaque fraction) for one block texture.

    netherite's palette wins where it covers the block, the measured vanilla
    tone covers the rest, and the golden angle is only for a name neither
    knows. Consecutive golden-angle indices land two fifths of the way round
    the hue circle, so any run of unknown blocks stays separated."""
    if name in TINTED:
        # one flat grey, because the colormap is what carries the colour and
        # the two are solved together
        _, spread, cover = VANILLA.get(name, (None, 34, 1.0))
        g = TINTED_GREY
        return (g, g, g), spread, cover
    if name in ORE_FLECK:
        # The FACE of an ore is plain stone in vanilla and the fleck is the
        # whole cue. Taking the texture's own mean instead tints the rock
        # with the ore, which both looks wrong and eats the contrast the
        # fleck is there to provide: it put lapis on blue rock and gold on
        # yellow rock, so face and fleck sat a few dE apart.
        host = "netherrack" if name == "quartz_ore" else "stone"
        base, spread, cover = VANILLA[host]
        return lit(base), max(spread, VANILLA[name][1] // 2), cover
    if name in PALETTE_BY_NAME:
        _, spread, cover = VANILLA.get(name, (None, 34, 1.0))
        return lit(PALETTE_BY_NAME[name]), spread, cover
    if name in VANILLA:
        base, spread, cover = VANILLA[name]
        return lit(base), spread, cover
    r = Rng(fnv(name))
    hue = (index * 0.6180339887498949) % 1.0
    return lit(hsv(hue, 0.35 + r.below(30) / 100.0,
                   0.42 + r.below(38) / 100.0)), 34, 1.0


def pattern_of(name):
    return PATTERNS.get(name, "grain")


# Ore flecks, measured off a jar build's rendered faces. This is the one
# accent that cannot come from the tile's own tone: vanilla ores all share
# the same grey stone face and the fleck colour IS the whole cue. Deriving
# it from the base, which is what every other pattern does, put all seven
# ores within a few dE of each other and of their own stone, which quietly
# turned ore-discrimination tasks into a test of something else.
#
# These are ALBEDOS, read off the jar-built atlas the same way every other
# number in VANILLA was, and they go through lit() like the rest. Rendered
# fleck means were available too and were not used directly, because a
# rendered number is only meaningful next to the face factor it was taken
# at: gold measures (122,116,83) rendered, which divided by DAYLIGHT_FACE
# gives (137,130,93) and not the (252,225,117) the texture actually holds,
# because that reading came off a face shaded nearer 0.48 than 0.89. Mixing
# the two spaces is the mistake that made the whole world dark one revision
# ago, so the fleck is measured where the tone is measured.
ORE_FLECK = {
    "coal_ore": (58, 58, 58),
    "iron_ore": (200, 163, 138),
    "gold_ore": (252, 225, 117),
    "diamond_ore": (153, 230, 251),
    "lapis_ore": (24, 64, 177),
    "redstone_ore": (180, 2, 2),
    "emerald_ore": (67, 205, 114),
    "quartz_ore": (219, 206, 194),
}


def accent_of(name, base, spread):
    """A structural mark reads against the grain rather than through it, so
    it is pitched one spread below the tone rather than at a fixed step.

    Ores are the exception and carry their own colour, because theirs is
    not a mark ON the material, it is the material the block is named for.
    """
    if name in ORE_FLECK:
        return lit(ORE_FLECK[name])
    return shade(base, -max(10, spread // 3))


def fill_material(p, w, h, base, spread, rng):
    """Two octaves of grain at the vanilla spread.

    One octave is either mush or static. A coarse four pixel cell carries the
    block's own variation, which is what stops a wall of one block reading as
    a single flat slab, and the per-texel octave carries the material.

    Note what is NOT here: a darker pixel around the tile. Faces do have to
    stay countable, but a rim baked into a texture that tiles across a
    terrain surface joins up into a continuous grid, which is why the grass
    looked like wireframe. Separation is the renderer's job and it already
    does it, by shading each face off its normal.
    """
    cw = w // 4 + 1
    coarse = [[rng.spread(spread) * 7 // 10 for _ in range(cw)]
              for _ in range(h // 4 + 1)]
    for y in range(h):
        row = coarse[y // 4]
        for x in range(w):
            # the coarse octave carries most of it on purpose. A texture is
            # minified to a few pixels at any distance, and per-texel grain
            # averages away there while block-scale clumps survive, which is
            # what makes a rock wall read as rock rather than as a gradient.
            d = row[x // 4] + rng.spread(spread) * 35 // 100
            c = [clamp(base[k] + d) for k in range(3)]
            if spread > 20 and rng.below(32) == 0:
                # a mineral fleck. Vanilla dirt and gravel carry a handful of
                # grey texels that are nothing like the rest of the tile, and
                # they are most of why a wall of one block does not read as a
                # single colour once it is minified.
                g = (c[0] + c[1] + c[2]) // 3
                c = [clamp((v + 3 * g) // 4 + rng.spread(spread // 3))
                     for v in c]
            p[x, y] = (c[0], c[1], c[2], 255)


def block_tile(name, index, total, size=16, salt=0):
    """One block texture: base colour, a pattern, a darker rim.

    `salt` is the animation frame. Folding it into the seed is what
    makes a water or lava strip move rather than repeat one still."""
    base, spread, cover = tone_of(name, index, total)
    pat = pattern_of(name)
    accent = accent_of(name, base, spread)
    rng = Rng(fnv(name) ^ 0x5BF03635 ^ (salt * 0x9E3779B1))
    im = img(size, size)
    p = px_of(im)
    cut = CUTOUTS.get(name)

    if cut:
        _cutout(p, size, cut, base, accent, rng)
        return im

    fill_material(p, size, size, base, spread, rng)

    if pat == "planks":
        # a plank edge is a dark line with a lit one under it, which is what
        # separates the boards at a distance where the grain has averaged out
        for y in range(size):
            if y % 4 == 3:
                for x in range(size):
                    p[x, y] = shade(base, -max(16, spread // 2)) + (255,)
            elif y % 4 == 0:
                for x in range(size):
                    p[x, y] = shade(base, max(8, spread // 4)) + (255,)
        for y in range(size):
            if y % 8 < 3:
                p[(fnv(name) + y) % size, y] = accent + (255,)
    elif pat == "bark":
        for x in range(size):
            if (x + rng.below(2)) % 4 == 0:
                for y in range(size):
                    p[x, y] = shade(accent, rng.spread(6)) + (255,)
    elif pat == "rings":
        c = (size - 1) / 2.0
        for y in range(size):
            for x in range(size):
                d = int(max(abs(x - c), abs(y - c)))
                if d % 4 == 0:
                    p[x, y] = shade(accent, 16 + rng.spread(5)) + (255,)
    elif pat == "grid":
        for i in range(size):
            p[i, size // 2] = accent + (255,)
            p[size // 2, i] = accent + (255,)
            p[i, 0] = accent + (255,)
            p[0, i] = accent + (255,)
    elif pat == "tools":
        # the crafting-table face: a dark frame with two marks in it, so it
        # cannot be confused with a plank or a log side
        for i in range(2, size - 2):
            p[i, 2] = accent + (255,)
            p[i, size - 3] = accent + (255,)
            p[2, i] = accent + (255,)
            p[size - 3, i] = accent + (255,)
        for i in range(4, size - 4):
            p[i, i] = shade(accent, 20) + (255,)
            p[size - 1 - i, i] = shade(accent, 20) + (255,)
    elif pat == "brick":
        for y in range(size):
            if y % 4 == 0:
                for x in range(size):
                    p[x, y] = accent + (255,)
            elif y % 8 < 4:
                p[(y // 4 * 3) % size, y] = accent + (255,)
            else:
                p[(y // 4 * 3 + 8) % size, y] = accent + (255,)
    elif pat == "rubble":
        for _ in range(size * 3):
            x, y = rng.below(size), rng.below(size)
            p[x, y] = shade(accent, rng.spread(10)) + (255,)
    elif pat == "ore":
        # seven 2x2 clusters, each shaded a little so the ore reads as
        # mineral in rock rather than as flat stickers
        for _ in range(7):
            x, y = 2 + rng.below(size - 4), 2 + rng.below(size - 4)
            for k, (dx, dy) in enumerate(((0, 0), (1, 0), (0, 1), (1, 1))):
                d = rng.spread(12) + (6 if k == 0 else -6 if k == 3 else 0)
                p[x + dx, y + dy] = shade(accent, d) + (255,)
    elif pat == "leaves":
        # punch holes to the measured coverage, which for oak is 61 percent.
        # Solid leaves turn a canopy into a black ceiling; the sky coming
        # through the gaps is most of what makes a forest readable.
        holes = int(round(size * size * (1.0 - cover)))
        placed = 0
        guard = 0
        while placed < holes and guard < size * size * 8:
            guard += 1
            x, y = rng.below(size), rng.below(size)
            if p[x, y][3]:
                p[x, y] = (0, 0, 0, 0)
                placed += 1
    elif pat == "cracks":
        stage = int(name.rsplit("_", 1)[1]) if name[-1].isdigit() else 0
        im2 = img(size, size)
        p2 = px_of(im2)
        for _ in range((stage + 1) * 6):
            x, y = rng.below(size), rng.below(size)
            for k in range(rng.below(4) + 1):
                p2[min(size - 1, x + k), min(size - 1, y + k)] = (0, 0, 0, 190)
        return im2
    elif pat == "water":
        for y in range(size):
            for x in range(size):
                d = rng.spread(max(6, spread))
                p[x, y] = (clamp(base[0] + d), clamp(base[1] + d),
                           clamp(base[2] + d), 200)
        return im
    elif pat == "lava":
        for _ in range(size * 2):
            x, y = rng.below(size), rng.below(size)
            p[x, y] = shade(accent, rng.spread(12)) + (255,)
    elif pat == "furnace":
        for y in range(7, size - 2):
            for x in range(3, size - 3):
                p[x, y] = accent + (255,)
        for x in range(4, size - 4):
            p[x, size - 4] = (150, 150, 150, 255)
    elif pat == "cage":
        for i in range(0, size, 3):
            for j in range(size):
                p[i, j] = accent + (255,)
                p[j, i] = accent + (255,)
    elif pat == "tnt":
        for y in range(6, 10):
            for x in range(size):
                p[x, y] = accent + (255,)
    elif pat == "grass_side":
        for y in range(4):
            for x in range(size):
                d = rng.spread(max(8, spread // 2))
                p[x, y] = (clamp(accent[0] + d), clamp(accent[1] + d),
                           clamp(accent[2] + d), 255)
        for x in range(size):
            if rng.below(2):
                p[x, 4] = accent + (255,)
    elif pat == "fringe":
        im2 = img(size, size)
        p2 = px_of(im2)
        for y in range(size):
            for x in range(size):
                keep = y < 3 or (y < 6 and (x + y + rng.below(2)) % 2 == 0)
                if keep:
                    d = rng.spread(max(8, spread // 2))
                    p2[x, y] = (clamp(base[0] + d), clamp(base[1] + d),
                                clamp(base[2] + d), 255)
        return im2
    elif pat == "glassy":
        im2 = img(size, size)
        p2 = px_of(im2)
        for i in range(size):
            for x, y in ((i, 0), (i, size - 1), (0, i), (size - 1, i)):
                p2[x, y] = base + (255,)
        for i in range(2, size - 2, 5):
            p2[i, i] = base + (150,)
        return im2

    return im


def _cutout(p, size, kind, base, accent, rng):
    """Shapes that need transparency. A cross plant drawn as a solid square
    renders as a coloured slab standing in the grass, which is worse than
    wrong: it looks like a block the agent could mine."""
    def put(x, y, c, a=255):
        if 0 <= x < size and 0 <= y < size:
            p[x, y] = (c[0], c[1], c[2], a)

    mid = size // 2
    if kind in ("plant", "flower", "shroom"):
        stem = shade(base, -30) if kind != "shroom" else shade(base, -20)
        for y in range(mid - 2 if kind == "shroom" else 2, size):
            put(mid, y, stem)
            if kind == "plant" and y % 3 == 0:
                put(mid - 1 - rng.below(2), y, base)
                put(mid + 1 + rng.below(2), y, base)
        if kind == "flower":
            for dx in range(-2, 3):
                for dy in range(-2, 3):
                    if abs(dx) + abs(dy) <= 2:
                        put(mid + dx, 4 + dy, base)
        elif kind == "shroom":
            for dx in range(-4, 5):
                for dy in range(-2, 2):
                    if abs(dx) + abs(dy) <= 4:
                        put(mid + dx, mid + dy, base)
    elif kind == "pad":
        for y in range(size):
            for x in range(size):
                if abs(x - mid) + abs(y - mid) <= mid:
                    put(x, y, shade(base, rng.spread(8)))
    elif kind == "bars":
        for x in (mid - 1, mid):
            for y in range(size):
                put(x, y, base)
    elif kind == "edge":
        for x in range(size):
            for y in (0, 1):
                put(x, y, base)
    elif kind == "ladder":
        for y in range(size):
            put(2, y, base)
            put(size - 3, y, base)
        for y in range(2, size, 4):
            for x in range(2, size - 2):
                put(x, y, shade(base, 18))
    elif kind == "rail":
        for x in (4, size - 5):
            for y in range(size):
                put(x, y, (150, 150, 155))
        for y in range(1, size, 4):
            for x in range(2, size - 2):
                put(x, y, shade(base, -10))
    elif kind == "web":
        for i in range(size):
            put(i, i, (236, 236, 236))
            put(size - 1 - i, i, (236, 236, 236))
            if i % 4 == 0:
                for x in range(size):
                    put(x, i, (210, 210, 210))
    elif kind == "torch":
        for y in range(size // 2, size):
            put(mid, y, (140, 100, 50))
            put(mid - 1, y, (120, 86, 44))
        for dy in range(3):
            for dx in range(-1, 2):
                put(mid + dx, size // 2 - 1 - dy, accent)
    elif kind == "glassy":
        for i in range(size):
            for x, y in ((i, 0), (i, size - 1), (0, i), (size - 1, i)):
                put(x, y, base)


def item_icon(name, index, total, size=16):
    """A flat coloured token, which is what the engine's own pip fallback
    draws when a sprite is missing. Making it a shape would be inventing art
    the engine does not need; the colour is what tells two items apart."""
    r = Rng(fnv(name))
    if name.startswith("empty_armor_slot_"):
        # Slot.getSlotTexture's hints. Vanilla draws a dim silhouette on the
        # slot grey, and a bright colour here would read as a held item.
        im = img(size, size)
        p = px_of(im)
        for y in range(4, size - 3):
            for x in range(4, size - 3):
                if (x + y) % 7:
                    p[x, y] = (96, 96, 96, 255)
        return im
