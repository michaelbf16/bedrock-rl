# Default-skin rects in the 64x64 unwrap. game/hand.c textures the
# first-person arm from texU=40,texV=16 and the inventory preview walks the
# whole net, so painting the regions separately is what makes both read as a
# person instead of one coloured slab.
SKIN_HEAD = (0, 0, 32, 16)
SKIN_SHIRT = ((16, 16, 40, 32), (16, 32, 40, 48))
SKIN_LEGS = ((0, 16, 16, 32), (0, 32, 16, 48), (0, 48, 16, 64))
SKIN_ARMS = ((40, 16, 56, 32), (32, 48, 48, 64))
SKIN_TONE = (198, 152, 110)
SKIN_SLEEVE = (56, 132, 136)


def player_skin_png(name):
    rng = Rng(fnv(name))

    def paint(x0, y0, x1, y1, col, amp=7):
        for y in range(y0, y1):
            for x in range(x0, x1):
                d = rng.spread(amp)
                p[x, y] = (clamp(col[0] + d), clamp(col[1] + d),
                           clamp(col[2] + d), 255)

    im = img(64, 64)
    p = px_of(im)
    paint(0, 0, 64, 64, SKIN_TONE)
    for rect in SKIN_SHIRT:
        paint(rect[0], rect[1], rect[2], rect[3], SKIN_SLEEVE)
    for rect in SKIN_LEGS:
        paint(rect[0], rect[1], rect[2], rect[3], (62, 62, 132))
    # The arm net is four faces side by side. A sleeve across the top of it
    # and a shaded far side give the first-person hand something to be, since
    # a single flat fill there is the whole held arm in every frame.
    for x0, y0, x1, y1 in SKIN_ARMS:
        paint(x0, y0, x1, y1, SKIN_TONE, 5)
        paint(x0, y0, x1, y0 + 4, SKIN_SLEEVE, 5)
        for x in range(x0 + 8, x1):
            for y in range(y0, y1):
                p[x, y] = shade(p[x, y][:3], -22) + (255,)
        for y in range(y0 + 4, y1):
            p[x0, y] = shade(p[x0, y][:3], -16) + (255,)
    for y in range(4, 12):                       # hair on the head rect
        for x in range(8, 16):
            p[x, y] = (68, 44, 26, 255)
    for x in (10, 13):                           # eyes on the face front
        p[x, 12] = (32, 32, 40, 255)
        p[x, 13] = (240, 240, 240, 255)
    return im


def skin_png(name, w=64, h=64):
    """A player or mob skin. The renderers read sub-rects of these by
    hand written UVs, so what matters is that every texel is opaque and the
    body reads as one colour; a transparent one leaves holes in the model."""
    rng = Rng(fnv(name))
    base = hsv((fnv(name) % 997) / 997.0, 0.42, 0.62)
    im = img(w, h, base + (255,))
    p = px_of(im)
    for y in range(h):
        for x in range(w):
            d = rng.spread(7)
            p[x, y] = (clamp(base[0] + d), clamp(base[1] + d),
                       clamp(base[2] + d), 255)
    return im


def strip_png(name, index, total, frames, size):
    """An animated block strip: frames stacked vertically, each the same
    tile redrawn with the frame folded into its seed, so the animation
    actually moves."""
    im = img(size, size * frames)
    for f in range(frames):
        im.paste(block_tile(name, index, total, size, salt=f + 1), (0, f * size))
    return im


def sun_png():
    im = img(32, 32)
    p = px_of(im)
    for y in range(32):
        for x in range(32):
            d = abs(x - 15.5) + abs(y - 15.5)
            if d < 15:
                p[x, y] = (255, 244, 190, 255)
    return im


def moon_phases_png():
    im = img(128, 64)
    p = px_of(im)
    for cell in range(8):
        ox, oy = (cell % 4) * 32, (cell // 4) * 32
        for y in range(32):
            for x in range(32):
                if abs(x - 15.5) + abs(y - 15.5) < 15:
                    p[ox + x, oy + y] = (226, 226, 232, 255)
    return im


def clouds_png():
    im = img(256, 256)
    p = px_of(im)
    rng = Rng(fnv("clouds"))
    grid = [[0] * 32 for _ in range(32)]
    for gy in range(32):
        for gx in range(32):
            grid[gy][gx] = 1 if rng.below(5) < 2 else 0
    for y in range(256):
        for x in range(256):
            if grid[y // 8][x // 8]:
                p[x, y] = (255, 255, 255, 200)
    return im


