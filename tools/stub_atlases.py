def ascii_png():
    """The 128x128 sheet, sixteen 8x8 cells to a row, character c at cell
    (c%16, c//16). That is where vanilla's FontRenderer looks and where
    hud.c font_init looks, so the layout is not ours to choose. hud.c also
    derives each character's advance from the rightmost opaque column of its
    cell, which is why the glyphs are left aligned in a five wide box."""
    out = img(128, 128)
    p = px_of(out)
    for code in range(32, 127):
        g = GLYPHS.get(chr(code))
        if not g:
            continue
        cx, cy = (code % 16) * 8, (code // 16) * 8
        for row, bits in enumerate(g.split("/")):
            for col, ch in enumerate(bits):
                if ch == "#":
                    p[cx + col, cy + row] = (255, 255, 255, 255)
    return out


