def stencil(p, x0, y0, rows, colour, rng, amp=6):
    """Draw one 9x9 HUD icon with the dark outline vanilla bakes into its.

    Without the outline a heart sitting on a bright sky is a pale smear.
    The shapes are all narrow enough to grow by a pixel inside their cell."""
    h, w = len(rows), len(rows[0])
    edge = shade(colour, -90)
    for y in range(h):
        for x in range(w):
            if rows[y][x] == "#":
                continue
            near = any(0 <= y + dy < h and 0 <= x + dx < w
                       and rows[y + dy][x + dx] == "#"
                       for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))
            if near:
                p[x0 + x, y0 + y] = edge + (255,)
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == "#":
                d = rng.spread(amp)
                p[x0 + x, y0 + y] = (clamp(colour[0] + d),
                                     clamp(colour[1] + d),
                                     clamp(colour[2] + d), 255)


