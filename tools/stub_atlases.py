# The renderer darkens everything on the way to the framebuffer, so a
# texture authored AT the palette renders below it. Measured rather than
# guessed: an engine whose every block is a flat 200 grey, player looking
# straight down at the top face of the block below in open sky, sampled
# across a whole world day.
#
#   world tick 0        121 of 200      the clock the world starts on
#   world tick 1000+    178 of 200      full daylight, and flat until dusk
#   world tick 14000    58 of 200       night, and tinted blue
#
# So a lit top face lands at 0.89 of what the texture holds, and the
# authored value is the palette divided by that. Two things follow.
#
# The first is that a stub build is about a tenth brighter than a jar build,
# because vanilla's own textures are authored at the palette rather than
# above it. That is deliberate: the palette is netherite's statement of what
# a block looks like, and hitting it on screen is the point.
#
# The second is worth knowing for any frame, not just these. Episodes start
# at world tick 0, which is the dim end of the curve, and a few hundred
# ticks never reach daylight. Short recordings are therefore lit at about
# 0.6 rather than 0.89. That is the clock, not the art.
DAYLIGHT_FACE = 0.89


def lit(rgb):
    """Authored albedo whose lit top face reads as `rgb`."""
    return tuple(clamp(round(v / DAYLIGHT_FACE)) for v in rgb)


