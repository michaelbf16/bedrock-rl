def particles_png(name, w, h):
    im = img(w, h)
    p = px_of(im)
    rng = Rng(fnv(name))
    for cy in range(0, h, 16):
        for cx in range(0, w, 16):
            col = hsv(rng.below(1000) / 1000.0, 0.5, 0.9)
            for y in range(2, 14):
                for x in range(2, 14):
                    p[cx + x, cy + y] = col + (200,)
    return im


# ----------------------------------------------------------------- packaging
def png_bytes(im):
    buf = io.BytesIO()
    im.save(buf, format="PNG")
    return buf.getvalue()


def build_pack(path):
    """Write the synthetic resource pack. Every member is drawn at its final
    size in RGBA, so nothing the engine's generators do to it resamples."""
    n_blocks = len(BLOCK_NAMES)
    n_items = len(ITEM_NAMES)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        def put(member, im):
            z.writestr(member, png_bytes(im))

        for i, name in enumerate(BLOCK_NAMES):
            if name in ANIMATED:
                frames, ft, size, seq_len = ANIMATED[name]
                put(TEX + "blocks/%s.png" % name,
                    strip_png(name, i, n_blocks, frames, size))
                seq = ([f for f in range(frames)] if seq_len == frames else
                       [f for f in range(frames)]
                       + [frames - 1 - f for f in range(seq_len - frames)])
                z.writestr(TEX + "blocks/%s.png.mcmeta" % name,
                           json.dumps({"animation": {"frametime": ft,
                                                     "frames": seq}}))
            elif name == "portal":
                put(TEX + "blocks/portal.png",
                    strip_png(name, i, n_blocks, PORTAL_FRAMES, 16))
            else:
                put(TEX + "blocks/%s.png" % name,
                    block_tile(name, i, n_blocks))
        for i, name in enumerate(ITEM_NAMES):
            put(TEX + "items/%s.png" % name, item_icon(name, i, n_items))
        put(TEX + "gui/container/inventory.png", inventory_png())
        put(TEX + "gui/container/crafting_table.png", crafting_table_png())
        put(TEX + "gui/container/furnace.png", furnace_png())
        put(TEX + "gui/container/generic_54.png", generic_54_png())
        put(TEX + "gui/widgets.png", widgets_png())
        put(TEX + "gui/icons.png", icons_png())
        put(TEX + "gui/bars.png", bars_png())
        put(TEX + "gui/options_background.png", options_background_png())
        put(TEX + "font/ascii.png", ascii_png())
        put(TEX + "misc/underwater.png", underwater_png())
        put(TEX + "colormap/grass.png", colormap_png(GRASS_CORNERS))
        put(TEX + "colormap/foliage.png", colormap_png(FOLIAGE_CORNERS))
        put(TEX + "environment/sun.png", sun_png())
        put(TEX + "environment/moon_phases.png", moon_phases_png())
        put(TEX + "environment/clouds.png", clouds_png())
        put(TEX + "environment/end_sky.png", end_sky_png())
        for member, w, h in MOBS:
            if member in ("steve.png", "alex.png"):
                put(TEX + "entity/" + member, player_skin_png(member))
            elif member in ("explosion.png",):
                put(TEX + "entity/" + member, particles_png(member, w, h))
            else:
                put(TEX + "entity/" + member, skin_png(member, w, h))
        put(TEX + "particle/particles.png",
            particles_png("particles.png", 128, 128))
        for layer in ARMOR_LAYERS:
            put(TEX + "models/armor/%s.png" % layer, skin_png(layer, 64, 32))
    return path


def digests(assets):
    out = {}
    for h in HEADERS:
        with open(os.path.join(assets, h), "rb") as f:
            out[h] = hashlib.sha256(f.read()).hexdigest()
    return out


def stamp(assets):
    """Prepend the provenance banner and record what was generated."""
    for h in HEADERS:
        p = os.path.join(assets, h)
        with open(p, "r") as f:
            body = f.read()
        if body.startswith("/* STUB TEXTURES"):
            continue
        with open(p, "w") as f:
            f.write(BANNER + body)
    d = digests(assets)
    with open(os.path.join(assets, "STUB_ATLASES"), "w") as f:
        f.write("stub_atlases.py v%d\n" % STUB_VERSION)
        for h in HEADERS:
            f.write("%s  %s\n" % (d[h], h))
    root = os.path.dirname(os.path.dirname(assets))
    digest = hashlib.sha256("".join(d[h] for h in HEADERS).encode()).hexdigest()
    with open(os.path.join(root, ".bedrock-rl-assets"), "w") as f:
        f.write("kind=procedural\n")
        f.write("source=bedrock-rl-stub-atlases-v%d\n" % STUB_VERSION)
        f.write("sha256=%s\n" % digest)
    return d


def generate(netherite_home, keep_pack=None):
    assets = os.path.join(netherite_home, "magma", "assets")
    if not os.path.isdir(assets):
        raise SystemExit("no magma/assets under " + netherite_home)
    tmp = tempfile.mkdtemp(prefix="stub_pack_")
    pack = build_pack(os.path.join(tmp, "stub_resources.jar"))
    env = dict(os.environ, MC_JAR=pack)
    subprocess.run(["bash", "scripts/bootstrap_assets.sh"],
                   cwd=netherite_home, env=env, check=True)
    d = stamp(assets)
    if keep_pack:
        os.replace(pack, keep_pack)
    else:
        os.remove(pack)
        os.rmdir(tmp)
    return d


def main():
    ap = argparse.ArgumentParser(
        description="generate netherite's texture headers without a jar")
    ap.add_argument("--netherite-home",
                    default=os.environ.get("NETHERITE_HOME",
                                           os.path.expanduser("~/netherite")))
    ap.add_argument("--keep-pack", metavar="PATH",
                    help="write the synthetic resource pack here for "
                         "inspection instead of deleting it")
    ap.add_argument("--print-digests", action="store_true",
                    help="print each header's sha256, which is how two "
                         "generations are compared")
    a = ap.parse_args()
    d = generate(os.path.expanduser(a.netherite_home), a.keep_pack)
    if a.print_digests:
        for h in HEADERS:
            print("%s  %s" % (d[h], h))
    print("stub atlases generated in %s/magma/assets (v%d)"
          % (a.netherite_home, STUB_VERSION))
    return 0


if __name__ == "__main__":
    sys.exit(main())
