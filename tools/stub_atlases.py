# ------------------------------------------------------------- panel drawing
def panel(w, h):
    """Vanilla container chrome: black outline, two pixel light bevel top and
    left, two pixel shadow bottom and right, flat face between them, corners
    cut. Reproduced procedurally rather than lifted, and the five greys are
    the module constants above."""
    im = img(w, h)
    p = px_of(im)
    for y in range(h):
        for x in range(w):
            dl, dt, dr, db = x, y, w - 1 - x, h - 1 - y
            if min(dl + dt, dr + dt, dl + db, dr + db) < 2:
                continue                                   # cut corner
            if min(dl, dt, dr, db) == 0:
                p[x, y] = PANEL_EDGE + (255,)
                continue
            light = dt <= 2 or dl <= 2 or dt + dl <= 6
            dark = db <= 2 or dr <= 2 or db + dr <= 6
            if light and dark:
                light = min(dt, dl) <= min(db, dr)
                dark = not light
            p[x, y] = ((PANEL_LIGHT if light else
                        PANEL_SHADOW if dark else PANEL_FACE) + (255,))
    return im


def slot(p, x, y, size=16):
    """One recessed slot. Content is size x size at (x,y); the recess is the
    square one pixel up and left, dark on its top and left and light on its
    bottom and right, which is what makes it read as a hole."""
    for i in range(-1, size + 1):
        p[x + i, y - 1] = SLOT_SHADOW + (255,)
        p[x - 1, y + i] = SLOT_SHADOW + (255,)
        p[x + i, y + size] = PANEL_LIGHT + (255,)
        p[x + size, y + i] = PANEL_LIGHT + (255,)
    p[x + size, y - 1] = SLOT_FACE + (255,)
    for j in range(size):
        for i in range(size):
            p[x + i, y + j] = SLOT_FACE + (255,)


def arrow(p, x, y, w, h, colour):
    """The grid-to-result arrow vanilla draws into the panel itself. Without
    it a screen shows two slot groups and no relation between them, which is
    exactly the thing the agent has to understand."""
    head = min(h, w)
    shaft = max(2, h // 3)
    top = y + (h - shaft) // 2
    for j in range(shaft):
        for i in range(w - head + 1):
            p[x + i, top + j] = colour + (255,)
    for j in range(head):
        reach = min(j, head - 1 - j)
        for i in range(reach + 1):
            p[x + w - head + i, y + j] = colour + (255,)


