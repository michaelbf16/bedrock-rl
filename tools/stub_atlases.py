# ---------------------------------------------------------------- randomness
def fnv(s):
    """FNV-1a over the sprite name. Python's hash() is salted per process
    and would make the build differ between two runs on one machine."""
    h = 0x811C9DC5
    for b in s.encode():
        h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    return h


class Rng:
    """xorshift32. Deterministic, seeded from a name, no library state."""

    def __init__(self, seed):
        self.s = (seed & 0xFFFFFFFF) or 0x9E3779B9

    def next(self):
        x = self.s
        x ^= (x << 13) & 0xFFFFFFFF
        x ^= x >> 17
        x ^= (x << 5) & 0xFFFFFFFF
        self.s = x
        return x

    def below(self, n):
        return self.next() % n

    def spread(self, n):
        """A signed value in [-n, n]."""
        return self.below(2 * n + 1) - n


def clamp(v):
    return 0 if v < 0 else 255 if v > 255 else int(v)


def shade(rgb, d):
    return (clamp(rgb[0] + d), clamp(rgb[1] + d), clamp(rgb[2] + d))


def hsv(h, s, v):
    """h,s,v in [0,1] to an 8-bit RGB triple. Integer-free but exact enough,
    and identical on every platform because it never touches libm."""
    i = int(h * 6) % 6
    f = h * 6 - int(h * 6)
    p, q, t = v * (1 - s), v * (1 - s * f), v * (1 - s * (1 - f))
    r, g, b = ((v, t, p), (q, v, p), (p, v, t),
               (p, q, v), (t, p, v), (v, p, q))[i]
    return (clamp(round(r * 255)), clamp(round(g * 255)), clamp(round(b * 255)))


