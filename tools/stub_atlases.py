def colormap_png(corners):
    """A biome colormap, bilinear across the four corners of the vanilla one.

    Vanilla indexes it by temperature across and humidity down, and the four
    corners it actually reaches are what these are: desert, plains, taiga and
    forest, read straight off the real map. Getting this right matters more
    than any single texture, because grass, leaves, tallgrass and vines are
    all near-grey textures that the colormap alone makes green. The earlier
    stub put the green in BOTH, which is what turned a canopy black.
    """
    hot_dry, hot_wet, cold_dry, cold_wet = corners
    im = img(256, 256)
    p = px_of(im)
    for j in range(256):
        wet = 1.0 - j / 255.0
        for i in range(256):
            hot = 1.0 - i / 255.0
            c = []
            for k in range(3):
                dry = hot_dry[k] * hot + cold_dry[k] * (1 - hot)
                wt = hot_wet[k] * hot + cold_wet[k] * (1 - hot)
                c.append(clamp(round(dry * (1 - wet) + wt * wet)))
            p[i, j] = tuple(c) + (255,)
    return im


# The colormaps are SOLVED, not copied. A tinted texture renders as
#
#   albedo * colormap / 255 * DAYLIGHT_FACE
#
# and the palette says what that has to come out as, so with the albedo
# pinned at TINTED_GREY the colormap is the only unknown. `solve` inverts
# it. The four corners keep vanilla's biome SHAPE, that a desert is
# yellower and a taiga greyer, by taking the vanilla corners' ratios about
# their own mean and re-centring them on the palette entry: grass block 2 at
# (95,159,53) and leaves 18 at (32,105,28).
_VANILLA_GRASS = ((191, 183, 85), (121, 192, 90), (150, 180, 120),
                  (134, 183, 131))
_VANILLA_FOLIAGE = ((174, 164, 42), (89, 174, 48), (120, 166, 80),
                    (104, 164, 100))


# What is left after solving. magma/core/shade.c composites a fragment as
# texel * tint * (lscalar * ao) * lightmap, with the tint AND the lightmap
# per channel, and then pulls every channel toward white by brightness_mix.
# So the residual is per channel by construction and no single constant
# lands. Solving against the mean of the four corners also aims at the
# average biome rather than the one the probe stands in. This is the gap
# that leaves, measured with the engine's own flat_shade instrument on a
# grass top face in open daylight, and applied to both maps because one
# biome column drives both.
COLORMAP_TRIM = (0.801, 1.0, 0.465)


def solve(corners, target):
    centre = [sum(c[k] for c in corners) / 4.0 for k in range(3)]
    want = [target[k] * COLORMAP_TRIM[k] * 255.0
            / (TINTED_GREY * DAYLIGHT_FACE) for k in range(3)]
    return tuple(tuple(clamp(round(c[k] * want[k] / centre[k]))
                       for k in range(3)) for c in corners)


